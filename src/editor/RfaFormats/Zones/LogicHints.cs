/// <summary>
/// Which classes of object the game's own scripts pass for a function's object parameter, most used
/// first (from all 1241 of the game's logic handlers: each handle resolved to its object's class), so
/// an editor can offer the objects that fit: triggers for "Trigger", squad spawn nodes for "Squad Spawn
/// Node". By the parameter's name, with the functions whose use differs from the name's listed apart.
