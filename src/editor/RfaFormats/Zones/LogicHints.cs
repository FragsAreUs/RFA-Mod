    public static IReadOnlyList<string> ClassesFor(string function, string parameter)
    {
        string name = parameter.Trim().ToLowerInvariant();
        if (ByFunction.TryGetValue($"{function}|{name}", out string? special)) return special.Split(' ');
        if (ByName.TryGetValue(name, out string? usual)) return usual.Split(' ');
        // Names the game's scripts never filled with an object of the zone: guess from the words.
        foreach (var (word, classes) in Words)
            if (name.Contains(word)) return classes.Split(' ');
        return [];
    }

